-- Reservas de canchas. Una fila por franja reservada.
BEGIN;

CREATE TABLE IF NOT EXISTS public.reserva (
    id_reserva     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cancha      BIGINT NOT NULL REFERENCES public.cancha (id_cancha),
    id_usuario     BIGINT NOT NULL REFERENCES public.usuario (id_usuario),
    fecha          DATE NOT NULL,
    hora_inicio    TIME NOT NULL,
    hora_fin       TIME NOT NULL,
    estado         VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE','CONFIRMADA','CANCELADA')),
    fecha_creacion TIMESTAMP NOT NULL DEFAULT now(),
    CHECK (hora_inicio < hora_fin)
);

CREATE INDEX IF NOT EXISTS reserva_cancha_fecha_idx ON public.reserva (id_cancha, fecha);
CREATE INDEX IF NOT EXISTS reserva_usuario_idx ON public.reserva (id_usuario);

COMMIT;