-- Tabla para almacenar información sobre las canchas
--
BEGIN;
CREATE TABLE IF NOT EXISTS public.cancha (
    id_cancha   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_complejo BIGINT NOT NULL REFERENCES public.complejo (id_complejo),
    nombre      VARCHAR(255) NOT NULL,
    precio_hora NUMERIC(10, 2) NOT NULL,
    estado      VARCHAR(255) NOT NULL DEFAULT 'ACTIVA',
    UNIQUE (id_complejo, nombre)
);

COMMIT;