-- Horario semanal de atención de cada complejo.
-- Un día cerrado no tiene fila: solo se guardan los días en que el complejo abre.
BEGIN;

CREATE TABLE IF NOT EXISTS public.horario_complejo (
    id_horario     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_complejo    BIGINT NOT NULL REFERENCES public.complejo (id_complejo),
    dia_semana     VARCHAR(10) NOT NULL
        CHECK (dia_semana IN ('LUNES','MARTES','MIERCOLES','JUEVES','VIERNES','SABADO','DOMINGO')),
    hora_apertura  TIME NOT NULL,
    hora_cierre    TIME NOT NULL,
    UNIQUE (id_complejo, dia_semana),
    CHECK (hora_apertura < hora_cierre)
);

COMMIT;